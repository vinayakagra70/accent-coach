export interface Lesson {
  id: string;
  title: string;
  /** Short label for the sound, e.g. "TH in think". */
  sound: string;
  kind: "consonant" | "vowel";
  /** What the target sound is (pose key). Several when the lesson contrasts two English sounds. */
  targets: { label: string; pose: string; contact?: Vec2 }[];
  /** What Indian-English speakers usually do instead (pose key). */
  habit: { label: string; pose: string; contact?: Vec2 };
  /** Plain-language explanation of the mistake. */
  mistake: string;
  /** How to make it, as body sensations. */
  steps: string[];
  /** Landmarks to label in 3D. "tip" follows the tongue tip. */
  labels: string[];
  words: string[];
  /** Minimal pairs: [target word, the word the habit makes it sound like]. */
  pairs: [string, string][];
  /** For vowels: which vowel the live mirror should aim at. */
  vowel?: string;
  /** For vowels: the vowel the habit lands on, shown on the chart. */
  habitVowel?: string;
}

